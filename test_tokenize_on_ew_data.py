#!/usr/bin/env python3
"""
test_tokenization.py

A lightweight script to visualize exactly how the FiscaAI dataset
is tokenized for the MedGemma + ICD-10 model. 
NO MODEL WEIGHTS ARE LOADED.
"""

import os
import torch
import argparse
from typing import List
from datasets import load_dataset, load_from_disk
from transformers import AutoTokenizer

# ============================================================
# TOKENIZER CLASSES
# ============================================================

class ICD10Tokenizer:
    def __init__(self, artifacts_dir):
        # We load the Hugging Face tokenizer that was generated by your tokenizer.py
        # It's specifically located inside the 'hf_tokenizer' subfolder if you followed tokenizer.py defaults.
        tokenizer_path = artifacts_dir
        if not os.path.exists(os.path.join(artifacts_dir, "vocab.txt")) and \
           os.path.exists(os.path.join(artifacts_dir, "hf_tokenizer")):
            tokenizer_path = os.path.join(artifacts_dir, "hf_tokenizer")
            
        self.tokenizer = AutoTokenizer.from_pretrained(tokenizer_path)
            
    def __len__(self):
        return len(self.tokenizer)
        
    def get_indices(self, code: str) -> List[int]:
        # Encode string code into token indices without adding special tokens like [CLS]/[SEP]
        return self.tokenizer.encode(code, add_special_tokens=False)


class MedicalMeadowICD10Dataset(torch.utils.data.Dataset):
    def __init__(self, data_list, icd10_tokenizer, text_tokenizer, max_text_length=2048, max_codes=1, max_code_tokens=10):
        self.dataset = data_list
        self.icd10_tokenizer = icd10_tokenizer
        self.text_tokenizer = text_tokenizer
        self.max_text_length = max_text_length
        self.max_codes = max_codes
        self.max_code_tokens = max_code_tokens

    def __len__(self):
        return len(self.dataset)

    def __getitem__(self, idx):
        item = self.dataset[idx]
        
        # Extract the schema columns
        system_prompt = item.get("system", "")
        user_prompt = item.get("user", "")
        assistant_response = item.get("assistant", "")
        
        # Format the prompt
        conversation = f"{system_prompt}\n\n### Question:\n{user_prompt}\n\n### Answer:\n{assistant_response}"
        
        # 1. Tokenize Text
        text_encoding = self.text_tokenizer(
            conversation,
            truncation=True,
            max_length=self.max_text_length,
            padding="max_length",
            return_tensors="pt"
        )
        
        # 2. Tokenize ICD-10 Codes
        raw_codes = item.get("codes", [])
        
        # Create a padded matrix [10 codes, 18 tokens per code] initialized to 0
        padded_matrix = torch.zeros((self.max_codes, self.max_code_tokens), dtype=torch.long)
        
        for i, code in enumerate(raw_codes[:self.max_codes]):
            # Get raw sub-token IDs for the code
            code_tokens = self.icd10_tokenizer.get_indices(code)
            
            # Truncate if a single code breaks into more than 18 sub-tokens (rare)
            code_tokens = code_tokens[:self.max_code_tokens]
            
            # Insert into our padded matrix row
            padded_matrix[i, :len(code_tokens)] = torch.tensor(code_tokens, dtype=torch.long)
            
        return {
            "input_ids": text_encoding["input_ids"].squeeze(0),
            "attention_mask": text_encoding["attention_mask"].squeeze(0),
            "icd10_indices": padded_matrix,
            # Returning raw strings/lists purely so we can print them in the test script
            "raw_conversation": conversation, 
            "raw_codes": raw_codes            
        }

# ============================================================
# MAIN TEST SCRIPT
# ============================================================

def main():
    parser = argparse.ArgumentParser(description="Visualize Tokenization")
    parser.add_argument('--dataset_path', type=str, default="FiscaAI___synth-ehr-icd10cm-prompt/default/0.0.0")
    # Path to where tokenizer.py saved its outputs
    parser.add_argument('--icd10_artifacts_dir', type=str, default="./icd10_tokenizer")
    # We only load the tokenizer for Gemma, NOT the 4B parameter model
    parser.add_argument('--model_name', type=str, default="unsloth/gemma-3-4b-it-bnb-4bit")
    parser.add_argument('--num_samples', type=int, default=2, help="Number of samples to visualize")
    args = parser.parse_args()

    print("\n--- 1. LOADING DATASET ---")
    dataset = None
    try:
        print("attempting local disk load...")
        dataset = load_from_disk(args.dataset_path)
    except Exception as e:
        
        print(f"Hub load failed ({e}), Attempting to load from Hugging Face Hub (or cache)...")
        try:
            dataset = load_dataset("FiscaAI/synth-ehr-icd10cm-prompt", cache_dir=args.dataset_path)
        except Exception as e2:
            print(f"Failed to load dataset: {e2}")
            return

    split_key = 'train' if 'train' in dataset else list(dataset.keys())[0]
    data = dataset[split_key]
    print(f"Loaded dataset split '{split_key}' with {len(data)} rows.")

    print("\n--- 2. LOADING TOKENIZERS ---")
    print(f"Loading Text Tokenizer ({args.model_name})...")
    text_tokenizer = AutoTokenizer.from_pretrained(args.model_name)
    if text_tokenizer.pad_token is None:
        text_tokenizer.pad_token = text_tokenizer.eos_token

    print(f"Loading ICD-10 Tokenizer ({args.icd10_artifacts_dir})...")
    icd10_tokenizer = ICD10Tokenizer(args.icd10_artifacts_dir)
    print(f"ICD-10 Vocab size: {len(icd10_tokenizer)}")

    print("\n--- 3. CREATING DATASET INSTANCE ---")
    # Setting max_text_length to 256 here just so the terminal output isn't overwhelmingly long
    test_dataset = MedicalMeadowICD10Dataset(
        data, icd10_tokenizer, text_tokenizer, 
        max_text_length=256, max_codes=10, max_code_tokens=18
    )

    print(f"\n--- 4. VISUALIZING {args.num_samples} SAMPLES ---")
    for i in range(args.num_samples):
        print(f"\n=======================================================")
        print(f"                     SAMPLE {i+1}")
        print(f"=======================================================")
        
        sample = test_dataset[i]
        
        # ----------------------------------------------------
        # 4A. Text Visualization
        # ----------------------------------------------------
        print("\n[A] TEXT TOKENIZATION:")
        raw_conv = sample['raw_conversation']
        
        # Print a snippet of the raw string
        snip_len = 100
        if len(raw_conv) > snip_len * 2:
            print(f"Raw String (truncated):\n{raw_conv[:snip_len]} ... [snip] ... {raw_conv[-snip_len:]}")
        else:
            print(f"Raw String:\n{raw_conv}")
            
        input_ids = sample['input_ids']
        valid_tokens = input_ids[sample['attention_mask'] == 1]
        print(f"\nText Tensor Shape (padded): {input_ids.shape}")
        print(f"Valid Tokens (non-padded count): {len(valid_tokens)}")
        
        # ----------------------------------------------------
        # 4B. ICD-10 Visualization
        # ----------------------------------------------------
        print("\n[B] ICD-10 TOKENIZATION:")
        raw_codes = sample['raw_codes']
        print(f"Raw Codes List: {raw_codes}")
        
        icd10_matrix = sample['icd10_indices']
        print(f"\nICD-10 Tensor Shape (Padded Matrix): {icd10_matrix.shape}")
        print("\nDeep Dive - How codes map to tensor rows:")
        for code_idx in range(test_dataset.max_codes):
            row = icd10_matrix[code_idx].tolist()
            
            if code_idx < len(raw_codes):
                code = raw_codes[code_idx]
                # Get indices again just to convert back to human-readable sub-tokens
                indices = icd10_tokenizer.get_indices(code)
                sub_tokens = icd10_tokenizer.tokenizer.convert_ids_to_tokens(indices)
                
                print(f"  Code {code_idx+1}: '{code}'")
                print(f"      Sub-tokens : {sub_tokens}")
                print(f"      Tensor Row : {row}")
            else:
                # Show what empty/padded rows look like
                print(f"  Row  {code_idx+1}: [Empty/Padding] -> {row}")
            
        if len(raw_codes) == 0:
            print("  (No codes in this sample)")

        print("=======================================================\n")

if __name__ == "__main__":
    main()
